// Writes src/components/sashimi/cghClinGenData.ts: the array-CGH browser's "ClinGen CNV regions" track data.
// Input dir: ucsc/<genome>.<track>.chr<N>.json read from
//   https://api.genome.ucsc.edu/getData/track?genome=<hg19|hg38>;track=<clinGenHaplo|clinGenTriplo>;chrom=chr<N>
// and the ClinGen recurrent CNV BED files (ClinGen_recurrent_CNV_V2.0-hg37.bed / -hg38.bed) from https://ftp.clinicalgenome.org/.
// Usage: node scripts/cgh-clingen-data.mjs <dir> <date read YYYY-MM-DD>
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
const [dir, read] = process.argv.slice(2); // dir holds the BED files and, in dir/ucsc, the JSON files
if (!dir || !read) { console.error('usage: node scripts/cgh-clingen-data.mjs <dir> <date read>'); process.exit(1); }
const out = {}; let newest = '';
for (const [g, b] of [['hg19', 'GRCh37'], ['hg38', 'GRCh38']]) {
  const reg = new Map();
  for (const f of readdirSync(`${dir}/ucsc`).filter(f => f.startsWith(g + '.') && f.endsWith('.json'))) {
    const d = JSON.parse(readFileSync(`${dir}/ucsc/${f}`, 'utf8')), t = d.track;
    if (!Array.isArray(d[t])) throw new Error(`${f}: no ${t} items`);
    for (const it of d[t]) {
      if (!/^ISCA-\d+$/.test(it.name)) continue;
      if (it.url !== `https://search.clinicalgenome.org/kb/gene-dosage/region/${it.name}`) throw new Error(`${it.name}: url ${it.url}`);
      const r = reg.get(it.name) ?? { c: it.chrom.replace(/^chr/, ''), s: it.chromStart, e: it.chromEnd, id: +it.name.slice(5), n: it.geneId, hi: null, ts: null, band: it.cytoBand, d: it.dateLastEvaluated };
      if (r.s !== it.chromStart || r.e !== it.chromEnd) console.warn(`${g} ${it.name}: haplo / triplo spans differ`);
      if (t === 'clinGenHaplo') r.hi = +it.haploScore; else r.ts = +it.triploScore;
      if (it.dateLastEvaluated > r.d) r.d = it.dateLastEvaluated;
      reg.set(it.name, r);
    }
  }
  const dosage = [...reg.values()].filter(r => r.hi === 3 || r.ts === 3).sort((a, b) => a.c.localeCompare(b.c, 'en', { numeric: true }) || a.s - b.s);
  for (const r of dosage) if (r.d > newest) newest = r.d;
  // BED: a track line, then a #chrom header (possibly on the same line): keep rows whose 2nd and 3rd fields are numbers
  const bed = readFileSync(`${dir}/ClinGen_recurrent_CNV_V2.0-${g === 'hg19' ? 'hg37' : 'hg38'}.bed`, 'utf8').split(/\r?\n/)
    .map(l => l.split('\t')).filter(f => /^chr/.test(f[0]) && /^\d+$/.test(f[1]) && /^\d+$/.test(f[2]))
    .map(f => [f[0].replace(/^chr/, ''), +f[1], +f[2], f[3].trim(), f[8]?.trim() === '0,0,0' ? 'b' : 'r']);
  out[b] = { dosage: dosage.map(r => [r.c, r.s, r.e, r.id, r.n, r.hi, r.ts, r.band, r.d]), recurrent: bed };
  console.log(b, dosage.length, 'dosage regions,', bed.length, 'BED rows');
}
const js = (a) => a.map(r => '  ' + JSON.stringify(r)).join(',\n');
writeFileSync('src/components/sashimi/cghClinGenData.ts', `/* eslint-disable */
// Generated by scripts/cgh-clingen-data.mjs, read ${read}. Do not edit by hand.
// 1. ClinGen dosage regions (ISCA-) with haploinsufficiency score 3 or triplosensitivity score 3, from the UCSC Genome
//    Browser tracks clinGenHaplo and clinGenTriplo (hg19 for GRCh37, hg38 for GRCh38), api.genome.ucsc.edu; newest
//    dateLastEvaluated: ${newest}. Row: chrom, start (0-based), end, ISCA number, name, HI, TS, cytoband, last evaluated.
//    Page: https://search.clinicalgenome.org/kb/gene-dosage/region/ISCA-<number>.
// 2. ClinGen recurrent CNV list v2.0 (no licence stated in the files):
//    https://ftp.clinicalgenome.org/ClinGen_recurrent_CNV_V2.0-hg37.bed (GRCh37 despite its name: db=hg19) and
//    https://ftp.clinicalgenome.org/ClinGen_recurrent_CNV_V2.0-hg38.bed. Row: chrom, start (0-based), end, name,
//    'r' recurrent region (orange in the file) or 'b' breakpoint / LCR segment (black).
export type ClinGenDosageRow = [string, number, number, number, string, number | null, number | null, string, string];
export type ClinGenBedRow = [string, number, number, string, 'r' | 'b'];
export const CLINGEN_READ = '${read}', CLINGEN_DOSAGE_EVALUATED = '${newest}';
${Object.entries(out).map(([b, o]) => `export const CLINGEN_DOSAGE_${b}: ClinGenDosageRow[] = [\n${js(o.dosage)},\n];\nexport const CLINGEN_RECURRENT_${b}: ClinGenBedRow[] = [\n${js(o.recurrent)},\n];`).join('\n')}
`);
